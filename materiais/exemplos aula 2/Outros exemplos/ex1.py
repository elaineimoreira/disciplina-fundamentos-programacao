idade = 12  # Define a variável idade com o valor 20

# Verifica se a idade é menor que 13
if idade < 13:
    print("Criança")  # Executa esta linha se a condição acima for verdadeira

# Se a primeira condição não for verdadeira, verifica se a idade é menor que 18
elif idade < 18:
    print("Adolescente")  # Executa esta linha se essa segunda condição for verdadeira

# Se nenhuma das condições anteriores for verdadeira
else:
    print("Adulto")  # Executa esta linha se todas as condições anteriores forem falsas
